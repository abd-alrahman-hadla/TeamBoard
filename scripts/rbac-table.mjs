#!/usr/bin/env node
// Renders the shared PERMISSIONS matrix into README.md between the rbac markers, so the docs
// can't drift from the code the API enforces.
//   pnpm docs:rbac            rewrite the table
//   pnpm docs:rbac --check    exit 1 if README.md is out of date (CI)
// Reads the built @teamboard/shared (pnpm --filter @teamboard/shared build).
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import prettier from 'prettier';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(join(root, 'packages/shared/package.json'));
const { PERMISSIONS, ROLES, can } = require('./dist/index.js');

const README = join(root, 'README.md');
const START = '<!-- rbac:start (generated by `pnpm docs:rbac` from packages/shared/src/roles.ts) -->';
const END = '<!-- rbac:end -->';

/** Footnotes for rules that live outside the matrix (shared/roles.ts helpers, checked in services). */
const NOTES = {
  'comment.update': '¹',
  'comment.delete': '²',
  'member.manage': '³',
  'workspace.leave': '⁴',
};
const FOOTNOTES = [
  '¹ Only the comment’s author can edit it.',
  '² The author, or an admin or owner, can delete a comment.',
  '³ Admins manage members and viewers and can grant up to admin; nobody changes or removes the owner, and ownership moves only by transfer.',
  '⁴ The owner has to transfer ownership before leaving.',
];

function renderTable() {
  const actions = Object.keys(PERMISSIONS);
  const header = `| Action | ${ROLES.map((r) => r[0] + r.slice(1).toLowerCase()).join(' | ')} |`;
  const divider = `| --- | ${ROLES.map(() => ':---:').join(' | ')} |`;
  const rows = actions.map((action) => {
    const cells = ROLES.map((role) => (can(role, action) ? '✅' : '—'));
    return `| \`${action}\`${NOTES[action] ?? ''} | ${cells.join(' | ')} |`;
  });
  return [header, divider, ...rows, '', ...FOOTNOTES.map((note) => `${note}  `)].join('\n').trimEnd();
}

/** The whole README with a fresh table, formatted exactly like `pnpm format` would. */
async function render(readme) {
  const start = readme.indexOf(START);
  const end = readme.indexOf(END);
  if (start === -1 || end === -1 || end < start) {
    throw new Error(`README.md needs the markers:\n${START}\n${END}`);
  }
  const raw = `${readme.slice(0, start + START.length)}\n\n${renderTable()}\n\n${readme.slice(end)}`;
  const options = (await prettier.resolveConfig(README)) ?? {};
  return prettier.format(raw, { ...options, filepath: README });
}

const current = readFileSync(README, 'utf8');
const next = await render(current);
if (process.argv.includes('--check')) {
  if (next !== current) {
    console.error('README.md RBAC table is out of date. Run `pnpm docs:rbac`.');
    process.exit(1);
  }
  console.log('README.md RBAC table is up to date.');
} else {
  writeFileSync(README, next);
  console.log(`README.md RBAC table: ${Object.keys(PERMISSIONS).length} actions × ${ROLES.length} roles.`);
}
